"""
metaheuristicas.py
==================
Metaheuristic optimisers for binary-vector search spaces.

All optimisers share the same interface so they are interchangeable in
run_experiment:

    best_solution, solutions_dict = optimiser(
        objective_function,   # f(vector) -> (cost: float, aux: any)
        chromosome_length,    # int
        **kwargs
    )

The objective_function must be minimised (lower cost = better).
Since SEQUENT maximises accuracy/F1, pass cost = -metric.

EXECUTION MODEL
---------------
The metaheuristic search is intentionally sequential. This avoids the
pickling/process overhead of dispatching quantum objective evaluations and
keeps the objective cache in one process. Use simulator/BLAS threads inside
each evaluation to exploit CPU resources.
"""

import math
import random
from typing import List

import numpy as np


# -----------------------------------------------------------------------------
#  SERIAL EVALUATION HELPERS
# -----------------------------------------------------------------------------

def _cache_lookup(objective_function, vec):
    cache = getattr(objective_function, "cache", None)
    key = str(vec)
    if cache is not None and key in cache:
        return cache[key]["cost"]
    cost, _ = objective_function(vec)
    if cache is not None and key in cache:
        return cache[key]["cost"]
    return cost


def _batch_eval_candidates(objective_function, candidates, n_workers=1):
    """Evaluate candidate vectors sequentially, preserving the shared cache."""
    cache = getattr(objective_function, "cache", None)
    for vec in candidates:
        if cache is None or str(vec) not in cache:
            objective_function(vec)


def _all_single_flip_neighbors(vector: List[int]):
    """Return full 1-flip neighbourhood as (bit_idx, candidate) tuples."""
    neigh = []
    for bit_idx in range(len(vector)):
        cand = vector[:]
        cand[bit_idx] ^= 1
        neigh.append((bit_idx, cand))
    return neigh


def _repair_zero_vector(vector, preferred_indices=None):
    """Avoid the degenerate all-zero mask by activating one preferred bit."""
    if not vector:
        return vector
    repaired = vector[:]
    if any(repaired):
        return repaired

    if preferred_indices:
        for idx in preferred_indices:
            if 0 <= idx < len(repaired):
                repaired[idx] = 1
                return repaired

    repaired[0] = 1
    return repaired


def _perturb_solution(vector, fraction, rng):
    """Flip a fraction of bits to diversify around the incumbent."""
    if not vector:
        return vector[:]
    out = vector[:]
    n_flip = max(1, int(round(fraction * len(out))))
    n_flip = min(n_flip, len(out))
    for idx in rng.sample(range(len(out)), n_flip):
        out[idx] ^= 1
    return out


# ─────────────────────────────────────────────────────────────────────────────
#  SIMULATED ANNEALING (binary)
# ─────────────────────────────────────────────────────────────────────────────

def simulated_annealing(
    objective_function,
    chromosome_length,
    initial_solution=None,
    initial_temp=100.0,
    cooling_rate=0.95,
    stopping_temp=1e-3,
    max_iterations=10,
    num_neighbors=5,
    seed=12345,
    n_workers=1,
):
    """
    Simulated annealing for binary vectors.

    At each temperature step, `num_neighbors` candidates are generated by
    flipping a random bit. When n_workers > 1, all candidates in a step
    are evaluated in parallel before the sequential accept/reject logic runs.
    """
    random.seed(seed)
    solutions_dict = getattr(objective_function, "cache", {})

    current = (
        initial_solution[:]
        if initial_solution is not None
        else [random.randint(0, 1) for _ in range(chromosome_length)]
    )
    current_cost = _cache_lookup(objective_function, current)
    best, best_cost = current[:], current_cost

    temp = initial_temp
    iteration = 0
    while temp > stopping_temp and iteration < max_iterations:
        candidates = []
        for _ in range(num_neighbors):
            c = current[:]
            c[random.randint(0, chromosome_length - 1)] ^= 1
            candidates.append(c)

        _batch_eval_candidates(objective_function, candidates, n_workers=n_workers)

        for candidate in candidates:
            candidate_cost = solutions_dict[str(candidate)]["cost"]
            delta = candidate_cost - current_cost
            if delta < 0 or random.random() < math.exp(-delta / temp):
                current, current_cost = candidate[:], candidate_cost
            if current_cost < best_cost:
                best, best_cost = current[:], current_cost

        temp *= cooling_rate
        iteration += 1
        print(f"  [SA] iter={iteration:>3}  T={temp:.4f}  best_cost={best_cost:.4f}")

    return best, solutions_dict


# ─────────────────────────────────────────────────────────────────────────────
#  TABU SEARCH (binary)
# ─────────────────────────────────────────────────────────────────────────────

def tabu_search(
    objective_function,
    chromosome_length,
    initial_solution=None,
    max_iterations=12,
    tabu_tenure=4,
    max_no_improve=4,
    neighborhood_sample_size=None,
    restart_fraction=0.2,
    seed=12345,
    n_workers=1,
):
    """
    Tabu Search for binary optimisation.

    Why it fits SEQUENT well
    ------------------------
    The SEQUENT search space is a small/medium binary mask over candidate
    entangling pairs. The objective is expensive and local 1-bit changes are
    meaningful, so an intensification-heavy local search with memory is a
    better complement to SA than a population method such as GA.

    Strategy
    --------
    - Neighbourhood: 1-bit flips around the current incumbent.
    - Memory: recently flipped bit positions stay tabu for `tabu_tenure`
      iterations to avoid short cycles.
    - Aspiration: a tabu move is still allowed if it improves the global best.
    - Diversification: after `max_no_improve` stagnant iterations, restart from
      the best solution found so far with a random multi-bit perturbation.

    Parameters
    ----------
    objective_function : callable
        f(vector: list[int]) -> (cost: float, aux: any). Minimised.
    chromosome_length : int
        Length of the binary vector.
    initial_solution : list[int] | None
        Starting point. Random if None.
    max_iterations : int
        Maximum number of tabu iterations.
    tabu_tenure : int
        How long a flipped bit remains tabu.
    max_no_improve : int
        Trigger diversification after this many non-improving iterations.
    neighborhood_sample_size : int | None
        If provided, evaluate only that many random 1-flip neighbours.
        If None, evaluate the full 1-flip neighbourhood.
    restart_fraction : float
        Fraction of bits to perturb during diversification restart.
    seed : int
        Random seed for reproducibility.
    n_workers : int
        Number of parallel workers for neighbourhood evaluation.

    Returns
    -------
    best_solution : list[int]
    solutions_dict : dict
        Every evaluated solution keyed by str(vector).
    """
    random.seed(seed)
    np.random.seed(seed)

    solutions_dict = getattr(objective_function, "cache", {})
    current = (
        initial_solution[:]
        if initial_solution is not None
        else [random.randint(0, 1) for _ in range(chromosome_length)]
    )
    current_cost = _cache_lookup(objective_function, current)
    best = current[:]
    best_cost = current_cost

    tabu_until = {}
    no_improve = 0

    for iteration in range(1, max_iterations + 1):
        neighbours = _all_single_flip_neighbors(current)
        if neighborhood_sample_size is not None and neighborhood_sample_size < len(neighbours):
            neighbours = random.sample(neighbours, neighborhood_sample_size)

        _batch_eval_candidates(
            objective_function,
            [cand for _, cand in neighbours],
            n_workers=n_workers,
        )

        best_admissible = None
        best_admissible_cost = float("inf")
        best_any = None
        best_any_cost = float("inf")
        chosen_bit = None

        for bit_idx, cand in neighbours:
            cand_cost = solutions_dict[str(cand)]["cost"]
            if cand_cost < best_any_cost:
                best_any = cand[:]
                best_any_cost = cand_cost

            is_tabu = tabu_until.get(bit_idx, 0) > iteration
            aspiration = cand_cost < best_cost
            if is_tabu and not aspiration:
                continue

            if cand_cost < best_admissible_cost:
                best_admissible = cand[:]
                best_admissible_cost = cand_cost
                chosen_bit = bit_idx

        if best_admissible is None:
            # If everything is tabu, still move to the best available neighbour.
            best_admissible = best_any[:]
            best_admissible_cost = best_any_cost
            diff_bit = next(
                idx for idx, (a, b) in enumerate(zip(current, best_admissible)) if a != b
            )
            chosen_bit = diff_bit

        current = best_admissible[:]
        current_cost = best_admissible_cost
        tabu_until[chosen_bit] = iteration + max(1, int(tabu_tenure))

        if current_cost < best_cost:
            best = current[:]
            best_cost = current_cost
            no_improve = 0
        else:
            no_improve += 1

        if no_improve >= max_no_improve:
            restart = best[:]
            n_flip = max(1, int(round(restart_fraction * chromosome_length)))
            for bit_idx in random.sample(range(chromosome_length), n_flip):
                restart[bit_idx] ^= 1
            _cache_lookup(objective_function, restart)
            current = restart
            current_cost = solutions_dict[str(restart)]["cost"]
            no_improve = 0
            print(
                f"  [TS] iter={iteration:>3}  diversify  "
                f"best_cost={best_cost:.4f}  evals={len(solutions_dict)}"
            )
            continue

        print(
            f"  [TS] iter={iteration:>3}  best_cost={best_cost:.4f}"
            f"  current_cost={current_cost:.4f}  evals={len(solutions_dict)}"
        )

    return best, solutions_dict


# ─────────────────────────────────────────────────────────────────────────────
#  GENETIC ALGORITHM (binary)
# ─────────────────────────────────────────────────────────────────────────────



def iterated_local_search(
    objective_function,
    chromosome_length,
    initial_solution=None,
    n_restarts=5,
    perturbation_strength=0.3,
    local_search_iters=15,
    local_search_initial_temp=5.0,
    local_search_cooling_rate=0.85,
    local_search_stopping_temp=1e-3,
    local_search_num_neighbors=3,
    seed=12345,
    n_workers=1,
    warm_start=None,
    repair=True,
):
    """
    Iterated Local Search for binary optimisation.

    This is the best follow-up to SA for SEQUENT because the objective is
    expensive and local 1-bit changes are informative. ILS therefore spends
    most of its budget on repeated local improvements instead of population
    drift.

    Workflow
    --------
    1. Start from a warm-start mask if available.
    2. Repair the degenerate all-zero mask if needed.
    3. Run a short simulated annealing local search.
    4. Perturb the best incumbent and repeat.

    Parameters
    ----------
    objective_function : callable
        f(vector: list[int]) -> (cost: float, aux: any). Minimised.
    chromosome_length : int
        Length of the binary vector.
    initial_solution : list[int] | None
        Explicit starting point.
    n_restarts : int
        Number of outer-loop launches, including the first local search.
    perturbation_strength : float
        Fraction of bits flipped when diversifying around the incumbent.
    local_search_iters : int
        Number of SA iterations per restart.
    local_search_initial_temp, local_search_cooling_rate, local_search_stopping_temp
        SA schedule for each local-search phase.
    local_search_num_neighbors : int
        Neighbours sampled per SA iteration.
    warm_start : list[int] | None
        Preferred initial mask derived from correlation strengths.
    repair : bool
        Repair all-zero masks by activating one preferred bit.
    """
    random.seed(seed)
    np.random.seed(seed)
    rng = random.Random(seed)
    solutions_dict = getattr(objective_function, "cache", {})

    preferred_source = warm_start if warm_start is not None else initial_solution
    preferred_indices = [i for i, bit in enumerate(preferred_source or []) if bit == 1]

    if warm_start is not None:
        incumbent = warm_start[:]
    elif initial_solution is not None:
        incumbent = initial_solution[:]
    else:
        incumbent = [rng.randint(0, 1) for _ in range(chromosome_length)]

    if repair:
        incumbent = _repair_zero_vector(incumbent, preferred_indices)

    best = incumbent[:]
    best_cost = _cache_lookup(objective_function, best)

    total_restarts = max(1, int(n_restarts))
    for restart_idx in range(total_restarts):
        if restart_idx == 0:
            seed_solution = incumbent[:]
        else:
            seed_solution = _perturb_solution(best, perturbation_strength, rng)
            if repair:
                seed_solution = _repair_zero_vector(seed_solution, preferred_indices)

        local_best, _ = simulated_annealing(
            objective_function,
            chromosome_length,
            initial_solution=seed_solution,
            initial_temp=local_search_initial_temp,
            cooling_rate=local_search_cooling_rate,
            stopping_temp=local_search_stopping_temp,
            max_iterations=local_search_iters,
            num_neighbors=local_search_num_neighbors,
            seed=seed + restart_idx,
            n_workers=n_workers,
        )
        local_cost = _cache_lookup(objective_function, local_best)

        if local_cost < best_cost:
            best = local_best[:]
            best_cost = local_cost

        print(
            f"  [ILS] restart={restart_idx + 1:>3}/{total_restarts}  "
            f"best_cost={best_cost:.4f}"
        )

    return best, solutions_dict

def genetic_algorithm(
    objective_function,
    chromosome_length,
    population_size=20,
    n_generations=10,
    crossover_rate=0.8,
    mutation_rate=None,
    tournament_size=3,
    elitism_count=1,
    seed=12345,
    n_workers=1,
):
    """
    Steady-state genetic algorithm for binary optimisation.

    This remains available for ablations / historical comparison, but for the
    current SEQUENT workload Tabu Search is generally a better second
    metaheuristic than GA because it spends fewer evaluations exploring
    globally-random candidates.
    """
    random.seed(seed)
    np.random.seed(seed)

    if mutation_rate is None:
        mutation_rate = 1.0 / chromosome_length

    solutions_dict = getattr(objective_function, "cache", {})

    def _batch_eval_population(pop):
        _batch_eval_candidates(objective_function, pop, n_workers=n_workers)
        return [solutions_dict[str(ind)]["cost"] for ind in pop]

    population = [
        [random.randint(0, 1) for _ in range(chromosome_length)]
        for _ in range(population_size)
    ]
    fitness = _batch_eval_population(population)

    best_idx = int(np.argmin(fitness))
    best = population[best_idx][:]
    best_cost = fitness[best_idx]
    print(f"  [GA] gen=  0  best_cost={best_cost:.4f}")

    for gen in range(1, n_generations + 1):
        ranked = sorted(range(population_size), key=lambda i: fitness[i])
        elites = [population[i][:] for i in ranked[:elitism_count]]

        new_population = elites[:]

        while len(new_population) < population_size:
            candidates_a = random.sample(range(population_size), tournament_size)
            parent_a = population[min(candidates_a, key=lambda i: fitness[i])][:]

            candidates_b = random.sample(range(population_size), tournament_size)
            parent_b = population[min(candidates_b, key=lambda i: fitness[i])][:]

            if random.random() < crossover_rate:
                child = [
                    parent_a[i] if random.random() < 0.5 else parent_b[i]
                    for i in range(chromosome_length)
                ]
            else:
                child = parent_a[:]

            child = [
                bit ^ 1 if random.random() < mutation_rate else bit
                for bit in child
            ]
            new_population.append(child)

        population = new_population
        fitness = _batch_eval_population(population)

        gen_best_idx = int(np.argmin(fitness))
        gen_best_cost = fitness[gen_best_idx]
        if gen_best_cost < best_cost:
            best_cost = gen_best_cost
            best = population[gen_best_idx][:]

        print(
            f"  [GA] gen={gen:>3}  best_cost={best_cost:.4f}"
            f"  gen_best={gen_best_cost:.4f}"
            f"  evals={len(solutions_dict)}"
        )

    return best, solutions_dict
